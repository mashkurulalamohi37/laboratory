# Range tuples: (sex | None, low, high, critical_low, critical_high, text_normal)
R = tuple[str | None, float | None, float | None, float | None, float | None, str | None]
Param = tuple[str, str, str | None, str | None, str, int, list[R], list[str] | None]


def p(
    code: str,
    name: str,
    unit: str | None,
    ranges: list[R],
    *,
    name_bn: str | None = None,
    result_type: str = "NUMERIC",
    decimals: int = 1,
    options: list[str] | None = None,
) -> Param:
    return (code, name, name_bn, unit, result_type, decimals, ranges, options)


def both(
    low: float | None, high: float | None, cl: float | None = None, ch: float | None = None
) -> list[R]:
    return [(None, low, high, cl, ch, None)]


def text(normal: str) -> list[R]:
    return [(None, None, None, None, None, normal)]


